// fileHeader writes the "generated" banner, package clause and import block.
func (g *generator) fileHeader(b *strings.Builder, imports ...string) {
	fmt.Fprintf(b, "// Code generated by lumex; DO NOT EDIT.\n//\n")
	fmt.Fprintf(b, "// Source: %s\n", g.origin)
	if g.version != "" {
		fmt.Fprintf(b, "// Bot API version: %s\n", g.version)
	}
	fmt.Fprintf(b, "\npackage %s\n\n", g.pkg)
	if len(imports) > 0 {
		fmt.Fprintf(b, "import (\n")
		for _, imp := range imports {
			fmt.Fprintf(b, "\t%q\n", imp)
		}
		fmt.Fprintf(b, ")\n\n")
	}
}

func formatGo(src string) ([]byte, error) {
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return []byte(src), fmt.Errorf("gofmt: %w", err)
	}
	return formatted, nil
}

// renderTypes emits types.go: object types, enumerations and the polymorphic
// (union) type machinery.
func (g *generator) renderTypes() ([]byte, error) {
	var b strings.Builder
	g.fileHeader(&b, "encoding/json", "fmt")

	section(&b, "Object types")
	for _, name := range g.order {
		g.renderStruct(&b, g.decls[name])
		g.renderFileMethods(&b, g.decls[name], false)
		b.WriteByte('\n')
	}

	section(&b, "Enumerations")
	for _, name := range g.enumOrder {
		g.renderEnum(&b, g.enums[name])
		b.WriteByte('\n')
	}

	section(&b, "Polymorphic (union) types")
	g.renderUnions(&b)
	g.renderUnionUnmarshalers(&b)

	g.renderStubs(&b)
	return formatGo(b.String())
}

// renderRequests emits requests.go: one payload struct per method.
func (g *generator) renderRequests() ([]byte, error) {
	var b strings.Builder
	g.fileHeader(&b) // plain structs, no imports needed
	section(&b, "Request payloads (method parameters)")
	for _, td := range g.requests {
		g.renderRequest(&b, td)
		g.renderFileMethods(&b, td, true)
		b.WriteByte('\n')
	}
	return formatGo(b.String())
}

// renderMethods emits methods.go: a typed wrapper on *Bot for every API method.
func (g *generator) renderMethods() ([]byte, error) {
	var b strings.Builder
	g.fileHeader(&b, "context", "encoding/json")
	section(&b, "Typed method wrappers (one per Bot API method)")
	for _, m := range g.methods {
		g.renderMethod(&b, m)
		b.WriteByte('\n')
	}
	return formatGo(b.String())
}

func (g *generator) renderMethod(b *strings.Builder, m methodInfo) {
	name := goTypeName(pascal(m.Name))

	sig := "ctx context.Context"
	var assigns []string
	for _, f := range m.Required {
		p := paramName(f)
		sig += ", " + p + " " + f.GoType
		assigns = append(assigns, f.GoName+": "+p)
	}
	if m.OptsType != "" {
		sig += ", opts ..." + m.OptsType
	}

	// Build the request from the required args plus (optionally) the opts. Opts
	// are variadic so callers can omit them entirely instead of passing nil.
	setup := ""
	arg := "&" + m.ReqType + "{" + strings.Join(assigns, ", ") + "}"
	if m.OptsType != "" {
		setup = fmt.Sprintf("\treq := %s\n\tif len(opts) > 0 {\n\t\treq.%s = opts[0]\n\t}\n", arg, m.OptsType)
		arg = "req"
	}

	retList := m.ReturnType + ", error"
	if m.MsgOrBool {
		retList = "*Message, bool, error"
	}

	fmt.Fprintf(b, "// %s calls the %q Bot API method.\n", name, m.Name)
	fmt.Fprintf(b, "func (b *Bot) %s(%s) (%s) {\n", name, sig, retList)
	b.WriteString(setup)
	switch {
	case m.MsgOrBool: // "Message or True": a Message unless it was an inline message, then true
		fmt.Fprintf(b, "\traw, err := b.BotClient.RequestWithContext(ctx, %q, %s)\n", m.Name, arg)
		fmt.Fprintf(b, "\tif err != nil {\n\t\treturn nil, false, err\n\t}\n")
		fmt.Fprintf(b, "\tvar msg Message\n")
		fmt.Fprintf(b, "\tif err := json.Unmarshal(raw, &msg); err != nil {\n")
		fmt.Fprintf(b, "\t\tvar ok bool\n")
		fmt.Fprintf(b, "\t\tif err := json.Unmarshal(raw, &ok); err != nil {\n\t\t\treturn nil, false, err\n\t\t}\n")
		fmt.Fprintf(b, "\t\treturn nil, ok, nil\n\t}\n")
		fmt.Fprintf(b, "\treturn &msg, true, nil\n}\n")
	case m.Decoder != "": // union result → decode into the concrete variant
		fmt.Fprintf(b, "\traw, err := b.BotClient.RequestWithContext(ctx, %q, %s)\n", m.Name, arg)
		fmt.Fprintf(b, "\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		fmt.Fprintf(b, "\treturn %s(raw)\n}\n", m.Decoder)
	case m.ReturnType == "json.RawMessage": // ambiguous result → raw bytes
		fmt.Fprintf(b, "\treturn b.BotClient.RequestWithContext(ctx, %q, %s)\n}\n", m.Name, arg)
	default:
		fmt.Fprintf(b, "\treturn Call[%s](ctx, b.BotClient, %q, %s)\n}\n", m.ReturnType, m.Name, arg)
	}
}

// renderConstants emits constants.go: string constant groups that are handy but
// not captured by field enums — update-type names (from the Update fields) and
// the message parse modes (from the "Formatting options" doc section).
func (g *generator) renderConstants() ([]byte, error) {
	var b strings.Builder
	g.fileHeader(&b)
	section(&b, "Constants")

	if u := g.decls["Update"]; u != nil {
		fmt.Fprintf(&b, "// Update-type names, e.g. for GetUpdatesRequest.AllowedUpdates.\nconst (\n")
		for _, f := range u.Fields {
			if f.JSONName == "update_id" {
				continue
			}
			fmt.Fprintf(&b, "\tUpdateType%s = %q\n", goFieldName(f.JSONName), f.JSONName)
		}
		fmt.Fprintf(&b, ")\n\n")
	}

	// Chat actions are listed in prose (sendChatAction.action) as <em>value</em>.
	if vals := emValues(g.fieldRawDesc(g.sections["sendChatAction"], "action")); len(vals) > 0 {
		fmt.Fprintf(&b, "// Chat actions for sendChatAction.action.\nconst (\n")
		for _, v := range vals {
			fmt.Fprintf(&b, "\tChatAction%s = %q\n", identPart(v), v)
		}
		fmt.Fprintf(&b, ")\n\n")
	}

	fmt.Fprintf(&b, "// Message parse modes for the parse_mode parameter.\nconst (\n")
	fmt.Fprintf(&b, "\tParseModeMarkdown   = %q\n", "Markdown")
	fmt.Fprintf(&b, "\tParseModeMarkdownV2 = %q\n", "MarkdownV2")
	fmt.Fprintf(&b, "\tParseModeHTML       = %q\n", "HTML")
	fmt.Fprintf(&b, ")\n")

	return formatGo(b.String())
}

var emValueRe = regexp.MustCompile(`<em>([a-z][a-z0-9_]*)</em>`)

// fieldRawDesc returns the (uncleaned) description cell of a field/parameter row.
func (g *generator) fieldRawDesc(section, jsonName string) string {
	t := tableRe.FindStringSubmatch(section)
	if t == nil {
		return ""
	}
	body := t[1]
	if m := tbodyRe.FindStringSubmatch(body); m != nil {
		body = m[1]
	}
	for _, row := range rowRe.FindAllStringSubmatch(body, -1) {
		cells := cellRe.FindAllStringSubmatch(row[1], -1)
		if len(cells) >= 3 && cleanText(cells[0][1]) == jsonName {
			return cells[len(cells)-1][1]
		}
	}
	return ""
}

// emValues extracts the distinct lowercase <em>value</em> tokens from raw HTML
// (used for enumerations documented in prose, like chat actions).
func emValues(raw string) []string {
	var vals []string
	seen := map[string]bool{}
	for _, m := range emValueRe.FindAllStringSubmatch(raw, -1) {
		if !seen[m[1]] {
			seen[m[1]] = true
			vals = append(vals, m[1])
		}
	}
	return vals
}

// renderHelpers emits helpers.go: the hand-crafted convenience types and their
// constructors (ReplyMarkup, InputFile, ChatID).
func (g *generator) renderHelpers() ([]byte, error) {
	var b strings.Builder
	g.fileHeader(&b, "encoding/json", "io", "os")
	section(&b, "Helper & polymorphic convenience types")
	g.renderReplyMarkup(&b)
	b.WriteString(runtimeSource)
	g.renderMediaConstructors(&b)
	return formatGo(b.String())
}

// renderMediaConstructors emits a New<Variant>(requiredFields…) *Variant helper
// for each variant of a file-carrying union (InputMedia, InputPaidMedia, …), so
// callers write telegram.NewInputMediaPhoto(file) instead of the &Variant{…}
// literal. Required-only fields become positional args; the discriminator is set
// automatically by the variant's MarshalJSON.
func (g *generator) renderMediaConstructors(b *strings.Builder) {
	for _, name := range g.unionOrder {
		if !g.fileCarrying[name] {
			continue
		}
		ui := g.unionInfos[name]
		for _, sub := range ui.Subtypes {
			if g.variantPrimary[sub] != name { // avoid duplicates across shared unions
				continue
			}
			td := g.decls[sub]
			if td == nil {
				continue
			}
			var params, assigns []string
			for _, f := range td.Fields {
				if f.OmitEmpty || f.JSONName == ui.DiscJSON {
					continue // optional fields and the discriminator are not args
				}
				p := paramName(f)
				params = append(params, p+" "+f.GoType)
				assigns = append(assigns, f.GoName+": "+p)
			}
			fmt.Fprintf(b, "\n// New%s builds a *%s from its required fields.\n", sub, sub)
			fmt.Fprintf(b, "func New%s(%s) *%s {\n\treturn &%s{%s}\n}\n",
				sub, strings.Join(params, ", "), sub, sub, strings.Join(assigns, ", "))
		}
	}
}

func section(b *strings.Builder, title string) {
	bar := strings.Repeat("=", len(title)+8)
	fmt.Fprintf(b, "// %s\n// === %s ===\n// %s\n\n", bar, title, bar)
}

func renderField(b *strings.Builder, f field) {
	if f.Comment != "" {
		fmt.Fprintf(b, "\t// %s %s\n", f.GoName, f.Comment)
	}
	tag := f.JSONName
	if f.OmitEmpty {
		tag += omitOption(f.JSONName)
	}
	fmt.Fprintf(b, "\t%s %s `json:%q`\n", f.GoName, f.GoType, tag)
}

// omitOption chooses the JSON omit directive for an optional field. Almost all
// use ",omitempty". allowed_updates is special: Telegram distinguishes an empty
// list [] ("subscribe to all update types except a few") from an absent field
// ("keep the previous setting"), so it must serialize an empty (non-nil) slice
// as [] — that needs ",omitzero" (omits only nil), not ",omitempty" (which also
// omits []). Requires Go 1.24+ and an encoding/json-compatible Marshaler.
func omitOption(jsonName string) string {
	if jsonName == "allowed_updates" {
		return ",omitzero"
	}
	return ",omitempty"
}

func (g *generator) renderStruct(b *strings.Builder, td *typeDecl) {
	writeDoc(b, td.Name, td.Doc)
	if len(td.Fields) == 0 {
		fmt.Fprintf(b, "type %s struct{}\n", td.Name)
		return
	}
	fmt.Fprintf(b, "type %s struct {\n", td.Name)
	for _, f := range td.Fields {
		renderField(b, f)
	}
	fmt.Fprintf(b, "}\n")
}

// renderRequest emits a request as an Opts struct (optional fields) plus the
// Request struct (required fields + an embedded Opts). The method (methods.go)
// takes the required fields as positional args and the Opts pointer.
func (g *generator) renderRequest(b *strings.Builder, td *typeDecl) {
	var required, optional []field
	for _, f := range td.Fields {
		if f.OmitEmpty {
			optional = append(optional, f)
		} else {
			required = append(required, f)
		}
	}

	opts := ""
	if len(optional) > 0 {
		opts = optsName(td.Name)
		fmt.Fprintf(b, "// %s holds the optional parameters for the %s request.\n", opts, td.Name)
		fmt.Fprintf(b, "type %s struct {\n", opts)
		for _, f := range optional {
			renderField(b, f)
		}
		fmt.Fprintf(b, "}\n\n")
	}

	writeDoc(b, td.Name, td.Doc)
	if len(required) == 0 && opts == "" {
		fmt.Fprintf(b, "type %s struct{}\n", td.Name)
		return
	}
	fmt.Fprintf(b, "type %s struct {\n", td.Name)
	for _, f := range required {
		renderField(b, f)
	}
	if opts != "" {
		fmt.Fprintf(b, "\t%s\n", opts) // optional params, promoted into the JSON
	}
	fmt.Fprintf(b, "}\n")
}

// computeFileCarrying finds every struct/union that transitively contains an
// *InputFile, and records which types are union variants (for receiver choice).
func (g *generator) computeFileCarrying() {
	g.isVariant = map[string]bool{}
	for _, ui := range g.unionInfos {
		for _, sub := range ui.Subtypes {
			g.isVariant[sub] = true
		}
	}

	g.fileCarrying = map[string]bool{}
	structs := func(yield func(*typeDecl)) {
		for _, n := range g.order {
			yield(g.decls[n])
		}
		for _, td := range g.requests {
			yield(td)
		}
	}
	for changed := true; changed; {
		changed = false
		structs(func(td *typeDecl) {
			if td == nil || g.fileCarrying[td.Name] {
				return
			}
			if g.structHasFile(td) {
				g.fileCarrying[td.Name] = true
				changed = true
			}
		})
		for _, ui := range g.unionInfos {
			if g.fileCarrying[ui.Name] {
				continue
			}
			for _, sub := range ui.Subtypes {
				if g.fileCarrying[sub] {
					g.fileCarrying[ui.Name] = true
					changed = true
					break
				}
			}
		}
	}
}

func (g *generator) structHasFile(td *typeDecl) bool {
	for _, f := range td.Fields {
		base := strings.TrimPrefix(strings.TrimPrefix(f.GoType, "[]"), "*")
		if base == "InputFile" || g.fileCarrying[base] {
			return true
		}
	}
	return false
}

// renderFileMethods emits the file-handling methods that make a value uploadable:
//
//   - Files() collects every uploadable *InputFile (recursing into nested media);
//     generated for any file-carrying type and any variant of a file-carrying
//     union (so the union interface's Files() is satisfied by all variants).
//   - Fields() (requests only) returns all parameters honouring omitempty; file
//     fields marshal to "attach://<id>" once the client assigns ids.
func (g *generator) renderFileMethods(b *strings.Builder, td *typeDecl, request bool) {
	// A variant of a file-carrying union must have Files() even if it holds no
	// file itself (to satisfy the interface).
	variantOfFileUnion := false
	if g.isVariant[td.Name] {
		for _, ui := range g.unionInfos {
			if g.fileCarrying[ui.Name] && contains(ui.Subtypes, td.Name) {
				variantOfFileUnion = true
				break
			}
		}
	}
	if !g.fileCarrying[td.Name] && !variantOfFileUnion {
		return
	}

	recv := "r " + td.Name
	if g.isVariant[td.Name] {
		recv = "m *" + td.Name // variants are held by pointer in the interface
	}
	self := recv[:1]

	fmt.Fprintf(b, "\n// Files returns the uploadable files nested in %s.\n", td.Name)
	fmt.Fprintf(b, "func (%s) Files() []*InputFile {\n\tvar fs []*InputFile\n", recv)
	for _, f := range td.Fields {
		ref := self + "." + f.GoName
		base := strings.TrimPrefix(strings.TrimPrefix(f.GoType, "[]"), "*")
		slice := strings.HasPrefix(f.GoType, "[]")
		switch {
		case base == "InputFile":
			fmt.Fprintf(b, "\tif %s != nil {\n\t\tfs = append(fs, %s)\n\t}\n", ref, ref)
		case g.fileCarrying[base] && slice && g.unions[base]:
			// []Union: interface elements are nil-able.
			fmt.Fprintf(b, "\tfor _, x := range %s {\n\t\tif x != nil {\n\t\t\tfs = append(fs, x.Files()...)\n\t\t}\n\t}\n", ref)
		case g.fileCarrying[base] && slice:
			// []Struct: value elements.
			fmt.Fprintf(b, "\tfor i := range %s {\n\t\tfs = append(fs, %s[i].Files()...)\n\t}\n", ref, ref)
		case g.fileCarrying[base]:
			fmt.Fprintf(b, "\tif %s != nil {\n\t\tfs = append(fs, %s.Files()...)\n\t}\n", ref, ref)
		}
	}
	fmt.Fprintf(b, "\treturn fs\n}\n")

	if !request {
		return
	}
	fmt.Fprintf(b, "\n// Fields returns the parameters of %s (implements Uploadable).\n", td.Name)
	fmt.Fprintf(b, "func (r %s) Fields() map[string]any {\n\tm := map[string]any{}\n", td.Name)
	for _, f := range td.Fields {
		if cond := g.fieldCondition(f); cond != "" {
			fmt.Fprintf(b, "\tif %s {\n\t\tm[%q] = r.%s\n\t}\n", cond, f.JSONName, f.GoName)
		} else {
			fmt.Fprintf(b, "\tm[%q] = r.%s\n", f.JSONName, f.GoName)
		}
	}
	fmt.Fprintf(b, "\treturn m\n}\n")
}

func contains(ss []string, s string) bool {
	for _, x := range ss {
		if x == s {
			return true
		}
	}
	return false
}

// fieldCondition returns the omitempty guard for an optional field, mirroring
// encoding/json's rules, or "" when the field is always included.
func (g *generator) fieldCondition(f field) string {
	if !f.OmitEmpty {
		return ""
	}
	ref := "r." + f.GoName
	switch t := f.GoType; {
	case t == "string" || g.enums[t] != nil:
		return ref + ` != ""`
	case t == "int64" || t == "float64":
		return ref + " != 0"
	case t == "bool":
		return ref
	case strings.HasPrefix(t, "*") || strings.HasPrefix(t, "[]") || t == "any" || t == "ReplyMarkup" || g.unions[t]:
		return ref + " != nil"
	default:
		return "" // value structs (ChatID, …): json omitempty is a no-op anyway
	}
}

func (g *generator) renderEnum(b *strings.Builder, e *enumDecl) {
	fmt.Fprintf(b, "// %s enumerates the allowed values of the %q field of %s.\n",
		e.Name, e.Field, e.Owner)
	fmt.Fprintf(b, "type %s string\n\nconst (\n", e.Name)
	for _, c := range e.Consts {
		fmt.Fprintf(b, "\t%s %s = %q\n", c.Name, e.Name, c.Value)
	}
	fmt.Fprintf(b, ")\n")
}

// commonField describes a field shared (with a consistent Go type) by every
// variant of a union — the basis for the interface's Get* accessors.
type commonField struct{ JSONName, GoName, GoType string }

func (g *generator) commonFields(ui *unionInfo) []commonField {
	first := g.decls[ui.Subtypes[0]]
	if first == nil {
		return nil
	}
	maps := make([]map[string]string, len(ui.Subtypes))
	for i, s := range ui.Subtypes {
		td := g.decls[s]
		if td == nil {
			return nil // a synthesized wrapper (RichText*) has no field table
		}
		m := map[string]string{}
		for _, f := range td.Fields {
			m[f.JSONName] = f.GoType
		}
		maps[i] = m
	}
	var out []commonField
	for _, f := range first.Fields {
		ok := true
		for _, m := range maps[1:] {
			if gt, present := m[f.JSONName]; !present || gt != f.GoType {
				ok = false
				break
			}
		}
		if ok {
			out = append(out, commonField{f.JSONName, f.GoName, f.GoType})
		}
	}
	return out
}

// exclusive reports whether every variant of the union belongs to it alone
// (no variant is shared with another union, which would clash on accessors).
func (g *generator) exclusive(ui *unionInfo) bool {
	for _, s := range ui.Subtypes {
		if g.sharedVariant[s] > 1 {
			return false
		}
	}
	return true
}

func accessorName(union, variant string) string {
	n := strings.TrimPrefix(variant, union)
	if n == "" {
		n = variant
	}
	return "As" + n
}

const accessorLimit = 12 // above this, a type switch is nicer than N² accessors

func (g *generator) renderUnions(b *strings.Builder) {
	for _, name := range g.unionOrder {
		ui := g.unionInfos[name]
		marker := "is" + name

		// Decide the ergonomic layer. It is generated only for unions the bot
		// receives and can inspect (decodable) whose variants are its own.
		ergonomic := ui.Decoder != "" && g.exclusive(ui)
		var getters []commonField
		if ergonomic && !ui.AllowsString && !ui.AllowsArray {
			getters = g.commonFields(ui)
		}
		accessors := ergonomic && len(ui.Subtypes) <= accessorLimit

		// Interface declaration.
		writeDoc(b, name, ui.Doc)
		fmt.Fprintf(b, "// It is implemented by: %s.\n", strings.Join(ui.Subtypes, ", "))
		if ergonomic && !accessors {
			fmt.Fprintf(b, "// (%d variants — use a type switch to access a specific one.)\n", len(ui.Subtypes))
		}
		fmt.Fprintf(b, "type %s interface {\n\t%s()\n", name, marker)
		if g.fileCarrying[name] {
			// Variants carry uploadable media; expose it for the client.
			fmt.Fprintf(b, "\tFiles() []*InputFile\n")
		}
		for _, f := range getters {
			fmt.Fprintf(b, "\tGet%s() %s\n", f.GoName, f.GoType)
		}
		if accessors {
			for _, sub := range ui.Subtypes {
				fmt.Fprintf(b, "\t%s() *%s\n", accessorName(name, sub), sub)
			}
		}
		fmt.Fprintf(b, "}\n\n")

		// Compile-time assertions that every variant satisfies the interface.
		// Variants are stored by pointer, so the pointer type is asserted.
		fmt.Fprintf(b, "var (\n")
		for _, sub := range ui.Subtypes {
			fmt.Fprintf(b, "\t_ %s = (*%s)(nil)\n", name, sub)
		}
		fmt.Fprintf(b, ")\n\n")

		// Marker methods sealing the interface to this package (pointer
		// receivers so variants are held without copying).
		for _, sub := range ui.Subtypes {
			fmt.Fprintf(b, "func (*%s) %s() {}\n", sub, marker)
		}
		b.WriteByte('\n')

		// Get* accessors for the fields common to every variant.
		for _, f := range getters {
			for _, sub := range ui.Subtypes {
				fmt.Fprintf(b, "func (v *%s) Get%s() %s { return v.%s }\n", sub, f.GoName, f.GoType, f.GoName)
			}
		}
		if len(getters) > 0 {
			b.WriteByte('\n')
		}

		// Typed As<Variant> accessors: type-safe, IDE-discoverable downcasts.
		if accessors {
			for _, sub := range ui.Subtypes {
				for _, target := range ui.Subtypes {
					tfn := accessorName(name, target)
					if target == sub {
						fmt.Fprintf(b, "func (v *%s) %s() *%s { return v }\n", sub, tfn, target)
					} else {
						fmt.Fprintf(b, "func (*%s) %s() *%s { return nil }\n", sub, tfn, target)
					}
				}
			}
			b.WriteByte('\n')
		}

		// Non-object alternatives (RichText may also be a String or an array).
		if ui.AllowsString {
			fmt.Fprintf(b, "// %sPlain is the bare-string form of %s.\n", name, name)
			fmt.Fprintf(b, "type %sPlain string\n\nfunc (*%sPlain) %s() {}\n\n", name, name, marker)
		}
		if ui.AllowsArray {
			fmt.Fprintf(b, "// %sSequence is the array form of %s.\n", name, name)
			fmt.Fprintf(b, "type %sSequence []%s\n\nfunc (*%sSequence) %s() {}\n\n", name, name, name, marker)
			fmt.Fprintf(b, "// UnmarshalJSON decodes each element of the sequence into its variant.\n")
			fmt.Fprintf(b, "func (s *%sSequence) UnmarshalJSON(data []byte) error {\n", name)
			fmt.Fprintf(b, "\tvar raws []json.RawMessage\n\tif err := json.Unmarshal(data, &raws); err != nil {\n\t\treturn err\n\t}\n")
			fmt.Fprintf(b, "\tout := make(%sSequence, len(raws))\n\tfor i, r := range raws {\n", name)
			fmt.Fprintf(b, "\t\tv, err := %s(r)\n\t\tif err != nil {\n\t\t\treturn err\n\t\t}\n\t\tout[i] = v\n\t}\n\t*s = out\n\treturn nil\n}\n\n", ui.Decoder)
		}

		// Foolproof marshaling: each variant this union defines forces its
		// discriminator constant so callers never have to set it by hand.
		if ui.DiscEnum != "" {
			for _, v := range ui.Variants {
				if g.variantPrimary[v.Type] != name {
					continue
				}
				g.renderVariantMarshal(b, v, ui)
			}
		}

		// Decoder.
		if ui.Decoder != "" {
			g.renderDecoder(b, ui)
		}
	}
}

func (g *generator) renderVariantMarshal(b *strings.Builder, v unionVariant, ui *unionInfo) {
	discGo := goFieldName(ui.DiscJSON)
	constName := ui.DiscEnum + identPart(v.DiscValue)
	fmt.Fprintf(b, "// MarshalJSON forces the %q discriminator of %s.\n", ui.DiscJSON, v.Type)
	fmt.Fprintf(b, "func (m %s) MarshalJSON() ([]byte, error) {\n", v.Type)
	fmt.Fprintf(b, "\ttype alias %s\n", v.Type)
	fmt.Fprintf(b, "\treturn json.Marshal(struct {\n")
	fmt.Fprintf(b, "\t\t%s %s `json:%q`\n", discGo, ui.DiscEnum, ui.DiscJSON)
	fmt.Fprintf(b, "\t\talias\n")
	fmt.Fprintf(b, "\t}{%s: %s, alias: alias(m)})\n}\n\n", discGo, constName)
}

func (g *generator) renderDecoder(b *strings.Builder, ui *unionInfo) {
	fmt.Fprintf(b, "// %s decodes a JSON %s into its concrete variant.\n", ui.Decoder, ui.Name)
	fmt.Fprintf(b, "func %s(data []byte) (%s, error) {\n", ui.Decoder, ui.Name)
	fmt.Fprintf(b, "\tif len(data) == 0 || string(data) == \"null\" {\n\t\treturn nil, nil\n\t}\n")

	if ui.Special == "maybeinaccessible" {
		fmt.Fprintf(b, "\tvar probe struct{ Date int64 `json:\"date\"` }\n")
		fmt.Fprintf(b, "\tif err := json.Unmarshal(data, &probe); err != nil {\n\t\treturn nil, err\n\t}\n")
		fmt.Fprintf(b, "\tif probe.Date == 0 {\n")
		fmt.Fprintf(b, "\t\tvar v InaccessibleMessage\n\t\terr := json.Unmarshal(data, &v)\n\t\treturn &v, err\n\t}\n")
		fmt.Fprintf(b, "\tvar v Message\n\terr := json.Unmarshal(data, &v)\n\treturn &v, err\n}\n\n")
		return
	}

	if ui.AllowsString {
		fmt.Fprintf(b, "\tif data[0] == '\"' {\n\t\tvar v %sPlain\n\t\terr := json.Unmarshal(data, &v)\n\t\treturn &v, err\n\t}\n", ui.Name)
	}
	if ui.AllowsArray {
		fmt.Fprintf(b, "\tif data[0] == '[' {\n\t\tvar v %sSequence\n\t\terr := json.Unmarshal(data, &v)\n\t\treturn &v, err\n\t}\n", ui.Name)
	}
	discGo := goFieldName(ui.DiscJSON)
	fmt.Fprintf(b, "\tvar probe struct{ %s string `json:%q` }\n", discGo, ui.DiscJSON)
	fmt.Fprintf(b, "\tif err := json.Unmarshal(data, &probe); err != nil {\n\t\treturn nil, err\n\t}\n")
	fmt.Fprintf(b, "\tswitch probe.%s {\n", discGo)
	for _, v := range ui.Variants {
		fmt.Fprintf(b, "\tcase %q:\n\t\tvar v %s\n\t\terr := json.Unmarshal(data, &v)\n\t\treturn &v, err\n", v.DiscValue, v.Type)
	}
	fmt.Fprintf(b, "\tdefault:\n\t\treturn nil, fmt.Errorf(\"unknown %s %s %%q\", probe.%s)\n", ui.Name, ui.DiscJSON, discGo)
	fmt.Fprintf(b, "\t}\n}\n\n")
}

