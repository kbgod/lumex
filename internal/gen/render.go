func (g *generator) renderStubs(b *strings.Builder) {
	var missing []string
	for name := range g.referenced {
		if _, ok := g.decls[name]; ok {
			continue
		}
		if g.unions[name] || g.emptyStruct[name] {
			continue
		}
		missing = append(missing, name)
	}
	if len(missing) == 0 {
		return
	}
	sort.Strings(missing)
	section(b, "Stubs for undocumented referenced types")
	for _, name := range missing {
		fmt.Fprintf(b, "type %s any\n\n", name)
	}
}

func writeDoc(b *strings.Builder, name, doc string) {
	if doc == "" {
		fmt.Fprintf(b, "// %s is an auto-generated Telegram Bot API type.\n", name)
		return
	}
	for _, line := range wrapText(name+" "+doc, 96) {
		fmt.Fprintf(b, "// %s\n", line)
	}
}
